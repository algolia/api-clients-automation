#!/usr/bin/env python3
"""Collect PR review context for any coding agent.

This harness is the agent-agnostic replacement for Claude Code-only wiring
($ARGUMENTS, /slash-command argument injection, gh-only commands). It:

- Parses a PR number or URL from ordinary CLI arguments
- Prefers the forge in a PR URL over the local git remote
- Collects metadata, diff, and review comments
- In local mode, merges unpushed working-tree changes
- Strips generated files from the review scope
"""

from __future__ import annotations

import argparse
import fnmatch
import json
import re
import shutil
import subprocess
import sys
import urllib.error
import urllib.request
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

GENERATED_PATH_GLOBS = (
    "tests/output/**/generated/**",
    "clients/**/*Client.cs",
)

GENERATED_HEADER_RE = re.compile(
    r"(?i)(<auto-generated>|auto[- ]generated|code generated|generated by|do not edit)"
)

GITHUB_PR_RE = re.compile(
    r"github\.com[:/](?P<owner>[^/]+)/(?P<repo>[^/#]+)(?:\.git)?(?:/pull/(?P<number>\d+))?",
    re.IGNORECASE,
)
ORIGIN_PR_RE = re.compile(
    r"(?:origin\.cursor\.com|cursor\.com/codebase|review\.cursor\.com)[:/].*?/(?P<owner>[^/]+)/(?P<repo>[^/#]+)",
    re.IGNORECASE,
)
PR_NUMBER_RE = re.compile(r"^(?:#)?(\d+)$")
PR_URL_NUMBER_RE = re.compile(r"/(?:pull|change|ch)/(\d+)(?:/|$)", re.IGNORECASE)

OVERLAY_INSTRUCTION_FILES = (
    ".agents/review-instructions.md",
    ".github/review-instructions.md",
    ".github/claude-review-instructions.md",
)

GH_PR_VIEW_FIELDS = (
    "title,body,author,baseRefName,headRefName,state,additions,deletions,"
    "changedFiles,labels,url,number,comments,reviews,reviewRequests"
)

REVIEWS_DIR = Path(".agents") / "reviews"
GITHUB_ACCEPT = "application/vnd.github+json"
GITHUB_USER_AGENT = "api-clients-review"
GITHUB_ID_RE = re.compile(r"^[A-Za-z0-9_.-]+$")
GITHUB_PR_NUMBER_RE = re.compile(r"^[0-9]+$")
REPORT_SLUG_RE = re.compile(r"^(?:[0-9]+|current)$")
ALLOWED_GITHUB_HOSTS = frozenset({"api.github.com", "github.com"})


class HarnessError(RuntimeError):
    """User-facing failure from the collect harness."""


@dataclass
class Target:
    mode: str  # "local" | "remote"
    number: str | None = None
    url: str | None = None
    extra_instructions: str = ""


@dataclass
class Forge:
    name: str  # "github" | "origin" | "git"
    owner: str | None = None
    repo: str | None = None
    remote_url: str = ""


@dataclass
class ReviewContext:
    mode: str
    forge: str
    number: str | None
    title: str = ""
    body: str = ""
    author: str = ""
    base_ref: str = ""
    head_ref: str = ""
    state: str = ""
    url: str = ""
    labels: list[str] = field(default_factory=list)
    overlay_instructions_path: str | None = None
    extra_instructions: str = ""
    comments: list[dict[str, Any]] = field(default_factory=list)
    skipped_generated_files: list[str] = field(default_factory=list)
    diff: str = ""
    changed_files: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    open_prs: list[dict[str, Any]] = field(default_factory=list)


def parse_target(tokens: list[str]) -> Target:
    """Parse a PR number/URL from ordinary argv, not client-specific $ARGUMENTS."""
    cleaned = [t.strip().strip("`") for t in tokens if t.strip()]
    if not cleaned:
        return Target(mode="local")

    first = cleaned[0]
    extra = " ".join(cleaned[1:])

    number_match = PR_NUMBER_RE.match(first)
    if number_match:
        return Target(mode="remote", number=number_match.group(1), extra_instructions=extra)

    url_number = PR_URL_NUMBER_RE.search(first)
    if first.startswith("http://") or first.startswith("https://") or url_number:
        number = url_number.group(1) if url_number else None
        return Target(mode="remote", number=number, url=first, extra_instructions=extra)

    raise HarnessError(
        f"Could not parse a PR number or URL from {first!r}. "
        "Pass nothing to review the current branch, or pass a number / PR URL."
    )


def _require_github_ids(owner: str | None, repo: str | None, number: str | None) -> tuple[str, str, str]:
    if not owner or not GITHUB_ID_RE.fullmatch(owner):
        raise HarnessError(f"Refusing unsafe GitHub owner {owner!r}")
    if not repo or not GITHUB_ID_RE.fullmatch(repo):
        raise HarnessError(f"Refusing unsafe GitHub repo {repo!r}")
    if not number or not GITHUB_PR_NUMBER_RE.fullmatch(number):
        raise HarnessError(f"Refusing unsafe PR number {number!r}")
    return owner, repo, number


def _report_slug(pr_number: str | None) -> str:
    slug = pr_number or "current"
    if not REPORT_SLUG_RE.fullmatch(slug):
        raise HarnessError(f"Refusing unsafe review report slug {slug!r}")
    return slug


def review_report_paths(repo_root: Path, pr_number: str | None) -> tuple[Path, Path]:
    """Return (/tmp copy, in-repo copy under .agents/reviews/)."""
    name = f"api-clients-review-{_report_slug(pr_number)}.md"
    reviews_dir = (repo_root / REVIEWS_DIR).resolve()
    repo_path = (reviews_dir / name).resolve()
    if repo_path.parent != reviews_dir:
        raise HarnessError("Review report path escaped .agents/reviews/")
    return Path("/tmp") / name, repo_path


def resolve_forge(repo_root: Path, target: Target) -> Forge:
    """Prefer the forge encoded in a PR URL over the local origin remote."""
    if target.url:
        hinted = detect_forge(repo_root, remote_url=target.url)
        if hinted.name in {"github", "origin"}:
            return hinted
    return detect_forge(repo_root)


def git_output(repo_root: Path, *args: str, check: bool = True) -> str:
    result = subprocess.run(
        ["git", *args],
        cwd=repo_root,
        check=False,
        capture_output=True,
        text=True,
    )
    if check and result.returncode != 0:
        raise HarnessError(result.stderr.strip() or f"git {' '.join(args)} failed")
    return result.stdout.strip()


def detect_forge(repo_root: Path, remote_url: str | None = None) -> Forge:
    url = remote_url if remote_url is not None else git_output(repo_root, "remote", "get-url", "origin")
    github = GITHUB_PR_RE.search(url)
    if github:
        return Forge(
            name="github",
            owner=github.group("owner"),
            repo=github.group("repo").removesuffix(".git"),
            remote_url=url,
        )
    origin = ORIGIN_PR_RE.search(url)
    if origin:
        return Forge(
            name="origin",
            owner=origin.group("owner"),
            repo=origin.group("repo").removesuffix(".git"),
            remote_url=url,
        )
    parsed = urlparse(url if "://" in url else f"ssh://{url}")
    host = (parsed.hostname or "").lower()
    if "github" in host:
        parts = [p for p in parsed.path.split("/") if p]
        owner = parts[0] if parts else None
        repo = parts[1].removesuffix(".git") if len(parts) > 1 else None
        return Forge(name="github", owner=owner, repo=repo, remote_url=url)
    if "cursor.com" in host or "origin." in host:
        parts = [p for p in parsed.path.split("/") if p]
        # origin.cursor.com/git/org/name.git
        if "git" in parts:
            git_idx = parts.index("git")
            parts = parts[git_idx + 1 :]
        owner = parts[0] if parts else None
        repo = parts[1].removesuffix(".git") if len(parts) > 1 else None
        return Forge(name="origin", owner=owner, repo=repo, remote_url=url)
    return Forge(name="git", remote_url=url)


def which(name: str) -> str | None:
    return shutil.which(name)


def run_cli(argv: list[str], cwd: Path) -> str:
    result = subprocess.run(argv, cwd=cwd, check=False, capture_output=True, text=True)
    if result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        if detail.lower().startswith("error:"):
            detail = detail.split(":", 1)[1].strip()
        raise HarnessError(detail or f"{argv[0]} exited {result.returncode}")
    return result.stdout


def path_is_generated(path: str) -> bool:
    normalized = path.lstrip("./").replace("\\", "/")
    for pattern in GENERATED_PATH_GLOBS:
        if fnmatch.fnmatch(normalized, pattern):
            return True
        # fnmatch does not treat ** as recursive on all Pythons; also check prefix forms
        if pattern.startswith("tests/output/") and "/generated/" in f"/{normalized}/":
            if normalized.startswith("tests/output/"):
                return True
        if pattern == "clients/**/*Client.cs" and normalized.startswith("clients/") and normalized.endswith("Client.cs"):
            return True
    return False


def content_looks_generated(text: str) -> bool:
    header = "\n".join(text.splitlines()[:12])
    return bool(GENERATED_HEADER_RE.search(header))


def filter_diff(diff: str) -> tuple[str, list[str], list[str]]:
    """Return (filtered_diff, kept_files, skipped_files)."""
    if not diff.strip():
        return "", [], []

    chunks: list[str] = []
    current: list[str] = []
    current_path: str | None = None
    kept_files: list[str] = []
    skipped: list[str] = []

    def flush() -> None:
        nonlocal current, current_path
        if not current:
            current_path = None
            return
        body = "\n".join(current)
        path = current_path or ""
        generated = path_is_generated(path) or content_looks_generated(body)
        if generated and path:
            skipped.append(path)
        else:
            chunks.append(body)
            if path:
                kept_files.append(path)
        current = []
        current_path = None

    for line in diff.splitlines():
        if line.startswith("diff --git "):
            flush()
            current = [line]
            match = re.search(r" b/(.+)$", line)
            current_path = match.group(1) if match else None
            continue
        if not current and line.startswith("+++ b/"):
            current = [line]
            current_path = line[6:]
            continue
        if current:
            current.append(line)
            if current_path is None and line.startswith("+++ b/"):
                current_path = line[6:]
    flush()

    filtered = "\n".join(chunks)
    if filtered and not filtered.endswith("\n"):
        filtered += "\n"
    return filtered, kept_files, skipped


def find_overlay_instructions(repo_root: Path) -> str | None:
    for relative in OVERLAY_INSTRUCTION_FILES:
        candidate = repo_root / relative
        if candidate.is_file():
            return relative
    return None


def merge_diffs(pushed: str, unstaged: str, staged: str) -> str:
    """Local working tree wins when the same file appears in pushed and local diffs."""
    by_path: dict[str, str] = {}
    order: list[str] = []

    def ingest(diff: str, replace: bool) -> None:
        if not diff.strip():
            return
        current: list[str] = []
        path: str | None = None
        for line in diff.splitlines():
            if line.startswith("diff --git "):
                if path is not None:
                    if replace or path not in by_path:
                        if path not in by_path:
                            order.append(path)
                        by_path[path] = "\n".join(current)
                current = [line]
                match = re.search(r" b/(.+)$", line)
                path = match.group(1) if match else f"unknown-{len(order)}"
                continue
            current.append(line)
        if path is not None:
            if replace or path not in by_path:
                if path not in by_path:
                    order.append(path)
                by_path[path] = "\n".join(current)

    ingest(pushed, replace=False)
    ingest(staged, replace=True)
    ingest(unstaged, replace=True)
    return "\n".join(by_path[p] for p in order if by_path[p]) + ("\n" if by_path else "")


def _author_login(value: Any) -> str:
    if isinstance(value, dict):
        return str(value.get("login") or value.get("name") or "")
    return str(value or "")


def _gh_repo_flags(forge: Forge) -> list[str]:
    if forge.owner and forge.repo:
        return ["-R", f"{forge.owner}/{forge.repo}"]
    return []


class _RejectRedirects(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):  # noqa: ANN001
        raise urllib.error.HTTPError(newurl, code, f"redirects disabled ({newurl})", headers, fp)


_GITHUB_OPENER = urllib.request.build_opener(_RejectRedirects)


def _assert_github_https_url(url: str, allowed_path_prefix: str | None = None) -> None:
    parsed = urlparse(url)
    host = (parsed.hostname or "").lower()
    if (
        parsed.scheme != "https"
        or host not in ALLOWED_GITHUB_HOSTS
        or parsed.username
        or parsed.password
        or parsed.port not in (None, 443)
        or ".." in parsed.path
        or "\\" in parsed.path
    ):
        raise HarnessError(f"Refusing non-allowlisted GitHub URL {url!r}")
    if allowed_path_prefix and not parsed.path.startswith(allowed_path_prefix):
        raise HarnessError(f"Refusing GitHub URL path {parsed.path!r}")


def _github_open(url: str, timeout: int, headers: dict[str, str]):
    _assert_github_https_url(url)
    request = urllib.request.Request(url, headers=headers)
    return _GITHUB_OPENER.open(request, timeout=timeout)


def _github_http_json(owner: str, repo: str, number: str, suffix: str) -> Any:
    owner, repo, number = _require_github_ids(owner, repo, number)
    if suffix not in {
        f"pulls/{number}",
        f"issues/{number}/comments",
        f"pulls/{number}/reviews",
        f"pulls/{number}/comments",
    }:
        raise HarnessError(f"Refusing GitHub API suffix {suffix!r}")
    path = f"/repos/{owner}/{repo}/{suffix}"
    url = f"https://api.github.com{path}"
    try:
        with _github_open(url, timeout=30, headers={"Accept": GITHUB_ACCEPT, "User-Agent": GITHUB_USER_AGENT}) as response:
            return json.loads(response.read().decode("utf-8"))
    except urllib.error.URLError as exc:
        raise HarnessError(f"GitHub HTTP {path} failed: {exc}") from exc


def _github_http_diff(owner: str, repo: str, number: str) -> str:
    owner, repo, number = _require_github_ids(owner, repo, number)
    url = f"https://github.com/{owner}/{repo}/pull/{number}.diff"
    _assert_github_https_url(url, allowed_path_prefix=f"/{owner}/{repo}/pull/")
    try:
        with _github_open(url, timeout=60, headers={"User-Agent": GITHUB_USER_AGENT}) as response:
            return response.read().decode("utf-8")
    except urllib.error.URLError as exc:
        raise HarnessError(f"GitHub HTTP fetch failed: {exc}") from exc


def collect_github_http(forge: Forge, target: Target) -> ReviewContext:
    if not forge.owner or not forge.repo or not target.number:
        raise HarnessError("GitHub HTTP fallback needs owner, repo, and PR number.")
    owner, repo, number = _require_github_ids(forge.owner, forge.repo, target.number)
    meta = _github_http_json(owner, repo, number, f"pulls/{number}")
    comments: list[dict[str, Any]] = []
    for item in _github_http_json(owner, repo, number, f"issues/{number}/comments") or []:
        comments.append(
            {
                "kind": "issue",
                "author": _author_login(item.get("user")),
                "body": item.get("body") or "",
            }
        )
    for item in _github_http_json(owner, repo, number, f"pulls/{number}/reviews") or []:
        comments.append(
            {
                "kind": "review",
                "author": _author_login(item.get("user")),
                "state": item.get("state") or "",
                "body": item.get("body") or "",
            }
        )
    for item in _github_http_json(owner, repo, number, f"pulls/{number}/comments") or []:
        comments.append(
            {
                "kind": "inline",
                "author": _author_login(item.get("user")),
                "path": item.get("path") or "",
                "line": item.get("line") or item.get("original_line"),
                "body": item.get("body") or "",
            }
        )
    labels = []
    for label in meta.get("labels") or []:
        if isinstance(label, dict):
            labels.append(str(label.get("name") or ""))
        else:
            labels.append(str(label))
    diff = _github_http_diff(owner, repo, number)
    return ReviewContext(
        mode=target.mode,
        forge="github",
        number=str(meta.get("number") or number),
        title=meta.get("title") or "",
        body=meta.get("body") or "",
        author=_author_login(meta.get("user")),
        base_ref=(meta.get("base") or {}).get("ref") or "",
        head_ref=(meta.get("head") or {}).get("ref") or "",
        state=meta.get("state") or "",
        url=meta.get("html_url") or target.url or "",
        labels=[label for label in labels if label],
        comments=comments,
        extra_instructions=target.extra_instructions,
        diff=diff,
        notes=["Collected via public GitHub HTTP API (gh unavailable or unauthenticated)."],
    )


def collect_github(repo_root: Path, target: Target, forge: Forge) -> ReviewContext:
    if not which("gh"):
        return collect_github_http(forge, target)

    repo_flags = _gh_repo_flags(forge)
    view_args = ["gh", "pr", "view", *repo_flags, "--json", GH_PR_VIEW_FIELDS]
    diff_args = ["gh", "pr", "diff", *repo_flags]
    if target.number:
        view_args.insert(3, target.number)
        diff_args.append(target.number)

    try:
        meta = json.loads(run_cli(view_args, repo_root))
    except HarnessError as exc:
        message = str(exc).lower()
        if "auth" in message or "gh_token" in message or "login" in message:
            return collect_github_http(forge, target)
        raise

    number = str(meta.get("number") or target.number or "")
    owner = forge.owner
    repo = forge.repo
    if not owner or not repo:
        try:
            name_with_owner = json.loads(
                run_cli(["gh", "repo", "view", *repo_flags, "--json", "nameWithOwner"], repo_root)
            )
            owner, _, repo = str(name_with_owner.get("nameWithOwner") or "").partition("/")
        except HarnessError:
            pass

    comments: list[dict[str, Any]] = []
    for item in meta.get("comments") or []:
        comments.append(
            {
                "kind": "issue",
                "author": _author_login(item.get("author")),
                "body": item.get("body") or "",
            }
        )
    for item in meta.get("reviews") or []:
        comments.append(
            {
                "kind": "review",
                "author": _author_login(item.get("author")),
                "state": item.get("state") or "",
                "body": item.get("body") or "",
            }
        )

    if owner and repo and number:
        try:
            inline = json.loads(
                run_cli(
                    ["gh", "api", f"repos/{owner}/{repo}/pulls/{number}/comments"],
                    repo_root,
                )
            )
            if isinstance(inline, list):
                for item in inline:
                    comments.append(
                        {
                            "kind": "inline",
                            "author": _author_login(item.get("user")),
                            "path": item.get("path") or "",
                            "line": item.get("line") or item.get("original_line"),
                            "body": item.get("body") or "",
                        }
                    )
        except HarnessError as exc:
            comments.append({"kind": "error", "body": f"Could not load inline comments: {exc}"})

    labels = []
    for label in meta.get("labels") or []:
        if isinstance(label, dict):
            labels.append(str(label.get("name") or ""))
        else:
            labels.append(str(label))

    return ReviewContext(
        mode=target.mode,
        forge="github",
        number=number or None,
        title=meta.get("title") or "",
        body=meta.get("body") or "",
        author=_author_login(meta.get("author")),
        base_ref=meta.get("baseRefName") or "",
        head_ref=meta.get("headRefName") or "",
        state=meta.get("state") or "",
        url=meta.get("url") or target.url or "",
        labels=[label for label in labels if label],
        comments=comments,
        extra_instructions=target.extra_instructions,
        diff=run_cli(diff_args, repo_root),
    )


def collect_origin(repo_root: Path, target: Target, forge: Forge | None = None) -> ReviewContext:
    if not which("origin"):
        raise HarnessError("Origin remote detected but the origin CLI is not on PATH.")

    view_target = target.number or target.url or ""
    repo_flags: list[str] = []
    if forge and forge.owner and forge.repo:
        repo_flags = ["-R", f"{forge.owner}/{forge.repo}"]
    json_fields = "number,title,body,status,author,url"
    view_cmd = ["origin", "pr", "view", *repo_flags]
    if view_target:
        view_cmd.append(view_target)

    meta: dict[str, Any] = {}
    notes: list[str] = []
    try:
        raw = run_cli([*view_cmd, "--json", json_fields], repo_root)
        parsed = json.loads(raw)
        meta = parsed if isinstance(parsed, dict) else {}
    except (HarnessError, json.JSONDecodeError) as exc:
        notes.append(f"origin --json view unavailable ({exc}); falling back to text.")
        text = run_cli(view_cmd, repo_root)
        meta = {"body": text}
        first_line = text.splitlines()[0] if text.strip() else ""
        meta["title"] = first_line

    diff_cmd = ["origin", "pr", "diff", *repo_flags]
    if view_target:
        diff_cmd.append(view_target)
    diff = run_cli([*diff_cmd, "--color", "never"], repo_root)

    comments: list[dict[str, Any]] = []
    try:
        comment_text = run_cli([*view_cmd, "--comments"], repo_root)
        if comment_text.strip():
            comments.append({"kind": "thread", "body": comment_text})
    except HarnessError as exc:
        notes.append(f"Could not load Origin comments: {exc}")

    number = str(meta.get("number") or target.number or "") or None
    author = _author_login(meta.get("author"))
    return ReviewContext(
        mode=target.mode,
        forge="origin",
        number=number,
        title=str(meta.get("title") or ""),
        body=str(meta.get("body") or ""),
        author=author,
        state=str(meta.get("status") or meta.get("state") or ""),
        url=str(meta.get("url") or target.url or ""),
        comments=comments,
        extra_instructions=target.extra_instructions,
        diff=diff,
        notes=notes,
    )


def list_open_prs(repo_root: Path, forge: Forge) -> list[dict[str, Any]]:
    if forge.name == "github" and which("gh"):
        raw = run_cli(["gh", "pr", "list", "--json", "number,title,headRefName,url,state"], repo_root)
        data = json.loads(raw)
        return data if isinstance(data, list) else []
    if forge.name == "origin" and which("origin"):
        raw = run_cli(["origin", "pr", "list", "--state", "open", "--json", "number,title,status"], repo_root)
        data = json.loads(raw)
        if isinstance(data, list):
            return data
        if isinstance(data, dict):
            return data.get("items") or data.get("pullRequests") or []
        return []
    return []


def collect(repo_root: Path, tokens: list[str]) -> ReviewContext:
    target = parse_target(tokens)
    forge = resolve_forge(repo_root, target)
    overlay = find_overlay_instructions(repo_root)

    if forge.name == "github":
        ctx = collect_github(repo_root, target, forge)
    elif forge.name == "origin":
        ctx = collect_origin(repo_root, target, forge)
    else:
        raise HarnessError(
            f"Unsupported git remote {forge.remote_url!r}. "
            "Need a GitHub or Origin remote, with gh or origin on PATH."
        )

    ctx.overlay_instructions_path = overlay
    ctx.mode = target.mode
    ctx.extra_instructions = target.extra_instructions

    if target.mode == "local":
        unstaged = git_output(repo_root, "diff", "HEAD", check=False)
        staged = git_output(repo_root, "diff", "--cached", check=False)
        ctx.diff = merge_diffs(ctx.diff, unstaged, staged)
        if unstaged or staged:
            ctx.notes.append("Local unpushed changes were merged into the review diff (local wins).")

    filtered, kept, skipped = filter_diff(ctx.diff)
    ctx.diff = filtered
    ctx.changed_files = kept
    ctx.skipped_generated_files = skipped
    return ctx


def render_markdown(ctx: ReviewContext) -> str:
    labels = ", ".join(ctx.labels) if ctx.labels else "(none)"
    lines = [
        f"# api-clients-review context ({ctx.mode} mode, {ctx.forge})",
        "",
        f"- PR: {ctx.number or '(current branch)'}",
        f"- Title: {ctx.title or '(none)'}",
        f"- Author: {ctx.author or '(unknown)'}",
        f"- State: {ctx.state or '(unknown)'}",
        f"- Base: {ctx.base_ref or '(unknown)'}  Head: {ctx.head_ref or '(unknown)'}",
        f"- URL: {ctx.url or '(none)'}",
        f"- Labels: {labels}",
        f"- Overlay instructions: {ctx.overlay_instructions_path or '(none)'}",
        f"- Extra instructions: {ctx.extra_instructions or '(none)'}",
        f"- Changed files (reviewable): {len(ctx.changed_files)}",
        f"- Skipped generated files: {len(ctx.skipped_generated_files)}",
        "",
    ]
    if ctx.notes:
        lines.append("## Notes")
        for note in ctx.notes:
            lines.append(f"- {note}")
        lines.append("")
    if ctx.skipped_generated_files:
        lines.append("## Skipped generated files")
        for path in ctx.skipped_generated_files:
            lines.append(f"- `{path}`")
        lines.append("")
    if ctx.changed_files:
        lines.append("## Reviewable files")
        for path in ctx.changed_files:
            lines.append(f"- `{path}`")
        lines.append("")
    lines.extend(["## Description", "", ctx.body.strip() or "(empty)", ""])
    if ctx.comments:
        lines.append("## Existing review comments")
        for comment in ctx.comments:
            author = comment.get("author") or "unknown"
            kind = comment.get("kind") or "comment"
            where = comment.get("path") or ""
            line_no = comment.get("line")
            loc = f" {where}:{line_no}" if where else ""
            lines.append(f"### {kind} by @{author}{loc}")
            lines.append("")
            lines.append(str(comment.get("body") or "").strip() or "(empty)")
            lines.append("")
    lines.extend(["## Diff", "", "```diff", ctx.diff.rstrip() or "(no non-generated changes)", "```", ""])
    return "\n".join(lines)


def write_sidecar(ctx: ReviewContext, markdown: str, repo_root: Path | None = None) -> list[Path]:
    slug = _report_slug(ctx.number)
    paths = [Path(f"/tmp/api-clients-review-context-{slug}.md")]
    written: list[Path] = []
    for path in paths:
        try:
            path.write_text(markdown, encoding="utf-8")
            written.append(path)
        except OSError:
            continue
    return written


def write_review_report(repo_root: Path, pr_number: str | None, text: str) -> list[Path]:
    tmp_path, repo_path = review_report_paths(repo_root, pr_number)
    repo_path.parent.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for path in (tmp_path, repo_path):
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Collect API-clients PR review context for any coding agent.",
    )
    parser.add_argument(
        "target",
        nargs="*",
        help="PR number, PR URL, or omit to review the current branch",
    )
    parser.add_argument("--repo-root", type=Path, default=None, help="Repository root (default: cwd)")
    parser.add_argument("--json", action="store_true", help="Print machine-readable JSON instead of markdown")
    parser.add_argument("--list", action="store_true", help="List open PRs and exit")
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    repo_root = (args.repo_root or Path.cwd()).resolve()
    if not (repo_root / ".git").exists() and not (repo_root / ".git").is_file():
        # allow tests to pass a git dir; otherwise still proceed if git rev-parse works
        try:
            git_output(repo_root, "rev-parse", "--is-inside-work-tree")
        except HarnessError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 2

    try:
        forge = detect_forge(repo_root)
        if args.list:
            prs = list_open_prs(repo_root, forge)
            if args.json:
                json.dump(prs, sys.stdout, indent=2)
                sys.stdout.write("\n")
            elif not prs:
                print("No open pull requests.")
            else:
                for pr in prs:
                    number = pr.get("number") or pr.get("id") or "?"
                    title = pr.get("title") or ""
                    print(f"#{number}  {title}")
            return 0

        ctx = collect(repo_root, list(args.target))
        if not ctx.changed_files and not ctx.diff.strip():
            ctx.notes.append("No changes to review.")

        payload = asdict(ctx)
        markdown = render_markdown(ctx)
        write_sidecar(ctx, markdown, repo_root)
        if args.json:
            json.dump(payload, sys.stdout, indent=2, default=str)
            sys.stdout.write("\n")
        else:
            sys.stdout.write(markdown)
            if not markdown.endswith("\n"):
                sys.stdout.write("\n")
        return 0
    except HarnessError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
